use std::time::Duration;

/// Where the block JSON fixtures live.
pub const FIXTURE_DIR: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/testdata");

/// Reads a block fixture (by file stem, e.g. `"361582"`) and caches it, so
/// serving the same block at many heights reads the file only once.
pub fn fixture(name: &str) -> Arc<String> {
    static CACHE: OnceLock<Mutex<HashMap<String, Arc<String>>>> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let mut cache = cache.lock().unwrap();
    Arc::clone(cache.entry(name.to_string()).or_insert_with(|| {
        let path = format!("{}/{}.json", FIXTURE_DIR, name);
        Arc::new(std::fs::read_to_string(&path).unwrap_or_else(|e| {
            panic!("could not read block fixture {}: {}", path, e);
        }))
    }))
}

/// Deserializes a block fixture into a [`Block`].
pub fn fixture_block(name: &str) -> Block {
    let body = fixture(name);
    let mut de = serde_json::Deserializer::from_str(&body);
    Block::deserialize(&mut de).expect("block fixture should deserialize")
}

/// Builds the stats of a fixture as if the block stats belonged to `height`
/// and as if they had been generated by version `stats_version` of the stats
/// code. Useful to pre-fill a database.
///
/// Only `block_stats` and `tx_stats` are moved to `height`; the other stats
/// structs keep their height private, so their rows stay at the fixture's own
/// height. That is enough for everything that looks at `block_stats`, which
/// is what decides whether a block gets fetched again.
pub fn fixture_stats(name: &str, height: i64, stats_version: i32) -> Stats {
    let mut stats = Stats::from_block(fixture_block(name)).expect("fixture stats");
    stats.block.height = height;
    stats.block.stats_version = stats_version;
    stats.tx.height = height;
    stats
}

/// Opens a migrated in-memory database.
pub fn memory_db() -> Arc<Mutex<SqliteConnection>> {
    let conn = db::open_db_and_run_migrations(":memory:").expect("in-memory database");
    Arc::new(Mutex::new(conn))
}

#[derive(QueryableByName)]
struct Count {
    #[diesel(sql_type = BigInt)]
    count: i64,
}

/// Number of rows in `table`.
pub fn row_count(conn: &mut SqliteConnection, table: &str) -> i64 {
    sql_query(format!("SELECT count(*) as count FROM {}", table))
        .get_result::<Count>(conn)
        .expect("row count")
        .count
}

/// A single integer column of a `block_stats` row, or `None` if there is no
/// such row.
pub fn block_stats_column(conn: &mut SqliteConnection, column: &str, height: i64) -> Option<i64> {
    sql_query(format!(
        "SELECT CAST({} AS BIGINT) as count FROM block_stats WHERE height = {}",
        column, height
    ))
    .get_results::<Count>(conn)
    .expect("block stats column")
    .first()
    .map(|c| c.count)
}

/// Initializes a logger for the tests. Set `RUST_LOG=debug` to see what the
/// pipeline is doing.
pub fn init_logger() {
    let _ = env_logger::Builder::from_env(env_logger::Env::default().default_filter_or("warn"))
        .is_test(true)
        .try_init();
}

/// A temporary directory that removes itself again when dropped.
pub struct TempDir {
    path: PathBuf,
}

impl TempDir {
    pub fn new(prefix: &str) -> TempDir {
        let mut path = std::env::temp_dir();
        path.push(format!(
            "mainnet-observer-{}-{}",
            prefix,
            Alphanumeric.sample_string(&mut rand::rng(), 12)
        ));
        std::fs::create_dir_all(&path).expect("create temp dir");
        TempDir { path }
    }

    pub fn path(&self) -> &Path {
        &self.path
    }

    pub fn str_path(&self) -> String {
        self.path.to_string_lossy().to_string()
    }

    /// A path inside the temporary directory. The file itself isn't created.
    pub fn child(&self, name: &str) -> PathBuf {
        self.path.join(name)
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

/// The REST endpoints the mock serves.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Endpoint {
    ChainInfo,
    BlockHash,
    Block,
}

/// A failure the mock injects before it answers a request normally.
#[derive(Clone, Debug)]
pub struct Fault {
    kind: FaultKind,
    /// How many requests are still answered with this fault.
    times: usize,
}

#[derive(Clone, Debug)]
enum FaultKind {
    /// Answer with an HTTP error status.
    Status(u16),
    /// Close the connection without answering.
    DropConnection,
    /// Wait before answering normally.
    Delay(Duration),
    /// Answer with a body of our choosing (status 200).
    Body(String),
    /// Answer with a body of `bytes` bytes.
    Oversized(usize),
}

impl Fault {
    /// Answer the next `times` requests with `status`.
    pub fn status(status: u16, times: usize) -> Fault {
        Fault {
            kind: FaultKind::Status(status),
            times,
        }
    }

    /// Answer every request with `status`.
    pub fn always_status(status: u16) -> Fault {
        Fault::status(status, usize::MAX)
    }

    /// Close the connection on the next `times` requests without answering.
    pub fn drop_connection(times: usize) -> Fault {
        Fault {
            kind: FaultKind::DropConnection,
            times,
        }
    }

    /// Wait `delay` before answering the next `times` requests.
    pub fn delay(delay: Duration, times: usize) -> Fault {
        Fault {
            kind: FaultKind::Delay(delay),
            times,
        }
    }

    /// Answer every request with `body` and status 200.
    pub fn body(body: &str) -> Fault {
        Fault {
            kind: FaultKind::Body(body.to_string()),
            times: usize::MAX,
        }
    }

    /// Answer every request with a body of `bytes` bytes.
    pub fn oversized(bytes: usize) -> Fault {
        Fault {
            kind: FaultKind::Oversized(bytes),
            times: usize::MAX,
        }
    }
}

/// What the mock serves for a block.
enum BlockBody {
    /// A fixture, served as the block with this hash at this height.
    Fixture {
        source: Arc<String>,
        hash: String,
        height: u64,
    },
    /// A body the test provided verbatim.
    Raw(Arc<String>),
}

impl BlockBody {
    fn render(&self) -> String {
        match self {
            BlockBody::Fixture {
                source,
                hash,
                height,
            } => {
                let body = replace_first_value(source, "hash", &format!("\"{}\"", hash));
                replace_first_value(&body, "height", &height.to_string())
            }
            BlockBody::Raw(body) => body.to_string(),
        }
    }
}

/// Replaces the value of the first `"<key>":` in `json`.
///
/// Bitcoin Core puts a block's own `hash` and `height` before the transaction
/// list, so the first occurrence is the block's and not one of a prevout.
fn replace_first_value(json: &str, key: &str, new_value: &str) -> String {
    let needle = format!("\"{}\":", key);
    let key_at = json
        .find(&needle)
        .unwrap_or_else(|| panic!("block JSON should have a {} field", key));
    let value_at = key_at + needle.len();
    let rest = &json[value_at..];
    let value_len = if let Some(in_string) = rest.strip_prefix('"') {
        in_string
            .find('"')
            .expect("block JSON string value should be terminated")
            + 2
    } else {
        rest.find(|c: char| !c.is_ascii_digit() && c != '-')
            .expect("block JSON number value should be terminated")
    };
    format!("{}{}{}", &json[..value_at], new_value, &rest[value_len..])
}

/// What the mock was asked for.
#[derive(Default, Debug)]
struct Requests {
    chain_info: usize,
    block_hash: usize,
    block: usize,
    /// The heights of all `/rest/blockhashbyheight/` requests, in the order
    /// they came in.
    heights: Vec<u64>,
}

struct Shared {
    blocks: u64,
    ibd: bool,
    verification_progress: f32,
    hash_by_height: HashMap<u64, String>,
    body_by_hash: HashMap<String, BlockBody>,
    faults: Mutex<HashMap<Endpoint, Fault>>,
    requests: Mutex<Requests>,
    connections: AtomicUsize,
    running: AtomicBool,
}

/// An in-process mock of Bitcoin Core's REST interface.
pub struct MockCore {
    host: String,
    port: u16,
    shared: Arc<Shared>,
    accept_handle: Option<JoinHandle<()>>,
}

impl MockCore {
    pub fn builder() -> MockCoreBuilder {
        MockCoreBuilder {
            blocks: 0,
            ibd: false,
            verification_progress: 1.0,
            hash_by_height: HashMap::new(),
            body_by_hash: HashMap::new(),
            faults: HashMap::new(),
        }
    }

    pub fn host(&self) -> &str {
        &self.host
    }

    pub fn port(&self) -> u16 {
        self.port
    }

    /// How often an endpoint was requested.
    pub fn requests(&self, endpoint: Endpoint) -> usize {
        let requests = self.shared.requests.lock().unwrap();
        match endpoint {
            Endpoint::ChainInfo => requests.chain_info,
            Endpoint::BlockHash => requests.block_hash,
            Endpoint::Block => requests.block,
        }
    }

    /// The block heights that were asked for, in the order they came in.
    pub fn requested_heights(&self) -> Vec<u64> {
        self.shared.requests.lock().unwrap().heights.clone()
    }

    /// The block heights that were asked for, sorted and without duplicates.
    pub fn requested_heights_sorted(&self) -> Vec<u64> {
        let mut heights = self.requested_heights();
        heights.sort_unstable();
        heights.dedup();
        heights
    }

    /// How many TCP connections the clients opened. A client that keeps its
    /// connections alive opens far fewer of them than it makes requests.
    pub fn connections(&self) -> usize {
        self.shared.connections.load(Ordering::Relaxed)
    }
}

impl Drop for MockCore {
    fn drop(&mut self) {
        self.shared.running.store(false, Ordering::Relaxed);
        if let Some(handle) = self.accept_handle.take() {
            let _ = handle.join();
        }
    }
}

pub struct MockCoreBuilder {
    blocks: u64,
    ibd: bool,
    verification_progress: f32,
    hash_by_height: HashMap<u64, String>,
    body_by_hash: HashMap<String, BlockBody>,
    faults: HashMap<Endpoint, Fault>,
}

/// The hash the mock hands out for a height. Not a real block hash, but a
/// valid one as far as the client is concerned.
pub fn hash_at_height(height: u64) -> String {
    format!("{:064x}", height)
}

impl MockCoreBuilder {
    /// The height the node reports as its tip.
    pub fn blocks(mut self, blocks: u64) -> Self {
        self.blocks = blocks;
        self
    }

    /// Makes the node claim it is still in initial block download.
    pub fn ibd(mut self, ibd: bool, verification_progress: f32) -> Self {
        self.ibd = ibd;
        self.verification_progress = verification_progress;
        self
    }

    /// Serves the fixture `name` as the block at `height`.
    pub fn block_at(mut self, height: u64, name: &str) -> Self {
        let hash = hash_at_height(height);
        self.hash_by_height.insert(height, hash.clone());
        self.body_by_hash.insert(
            hash.clone(),
            BlockBody::Fixture {
                source: fixture(name),
                hash,
                height,
            },
        );
        self
    }

    /// Serves the fixture `name` at every one of `heights`.
    pub fn blocks_at(mut self, heights: impl IntoIterator<Item = u64>, name: &str) -> Self {
        for height in heights {
            self = self.block_at(height, name);
        }
        self
    }

    /// Serves `body` verbatim as the block at `height`.
    pub fn raw_block_at(mut self, height: u64, body: impl Into<String>) -> Self {
        let hash = hash_at_height(height);
        self.hash_by_height.insert(height, hash.clone());
        self.body_by_hash
            .insert(hash, BlockBody::Raw(Arc::new(body.into())));
        self
    }

    /// Injects a failure on an endpoint.
    pub fn fault(mut self, endpoint: Endpoint, fault: Fault) -> Self {
        self.faults.insert(endpoint, fault);
        self
    }

    pub fn start(self) -> MockCore {
        let shared = Arc::new(Shared {
            blocks: self.blocks,
            ibd: self.ibd,
            verification_progress: self.verification_progress,
            hash_by_height: self.hash_by_height,
            body_by_hash: self.body_by_hash,
            faults: Mutex::new(self.faults),
            requests: Mutex::new(Requests::default()),
            connections: AtomicUsize::new(0),
            running: AtomicBool::new(true),
        });

        let listener = TcpListener::bind("127.0.0.1:0").expect("bind mock REST listener");
        listener
            .set_nonblocking(true)
            .expect("set listener non-blocking");
        let port = listener.local_addr().expect("local addr").port();

        let accept_shared = Arc::clone(&shared);
        let accept_handle = thread::spawn(move || {
            while accept_shared.running.load(Ordering::Relaxed) {
                match listener.accept() {
                    Ok((stream, _)) => {
                        accept_shared.connections.fetch_add(1, Ordering::Relaxed);
                        let shared = Arc::clone(&accept_shared);
                        // The connection threads are deliberately detached:
                        // they block on a read until the client closes the
                        // connection, which it does when the test's
                        // `RestClient` goes away.
                        thread::spawn(move || serve_connection(stream, shared));
                    }
                    Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                        thread::sleep(Duration::from_millis(5));
                    }
                    Err(_) => break,
                }
            }
        });

        MockCore {
            host: "127.0.0.1".to_string(),
            port,
            shared,
            accept_handle: Some(accept_handle),
        }
    }
}

fn serve_connection(stream: TcpStream, shared: Arc<Shared>) {
    stream.set_nonblocking(false).expect("blocking stream");
    let mut writer = stream.try_clone().expect("clone stream");
    let mut reader = BufReader::new(stream);

    loop {
        let mut request_line = String::new();
        match reader.read_line(&mut request_line) {
            Ok(0) | Err(_) => return, // the client hung up
            Ok(_) => {}
        }
        // Skip the headers, we don't need any of them.
        loop {
            let mut header = String::new();
            match reader.read_line(&mut header) {
                Ok(0) | Err(_) => return,
                Ok(_) => {}
            }
            if header == "\r\n" || header == "\n" {
                break;
            }
        }

        let path = request_line
            .split_whitespace()
            .nth(1)
            .unwrap_or("/")
            .to_string();
        if !handle_request(&mut writer, &shared, &path) {
            return;
        }
    }
}

/// Answers one request. Returns whether the connection should stay open.
fn handle_request(writer: &mut TcpStream, shared: &Arc<Shared>, path: &str) -> bool {
    let endpoint = if path == "/rest/chaininfo.json" {
        Some(Endpoint::ChainInfo)
    } else if path.starts_with("/rest/blockhashbyheight/") {
        Some(Endpoint::BlockHash)
    } else if path.starts_with("/rest/block/") {
        Some(Endpoint::Block)
    } else {
        None
    };

    let height = if endpoint == Some(Endpoint::BlockHash) {
        path.trim_start_matches("/rest/blockhashbyheight/")
            .trim_end_matches(".hex")
            .parse::<u64>()
            .ok()
    } else {
        None
    };

    {
        let mut requests = shared.requests.lock().unwrap();
        match endpoint {
            Some(Endpoint::ChainInfo) => requests.chain_info += 1,
            Some(Endpoint::BlockHash) => requests.block_hash += 1,
            Some(Endpoint::Block) => requests.block += 1,
            None => {}
        }
        if let Some(height) = height {
            requests.heights.push(height);
        }
    }

    if let Some(endpoint) = endpoint {
        if let Some(kind) = take_fault(shared, endpoint) {
            match kind {
                // A slow node still answers correctly, so only the timing
                // changes and the normal answer below is sent.
                FaultKind::Delay(delay) => thread::sleep(delay),
                kind => return apply_fault(writer, kind),
            }
        }
    }

    match endpoint {
        Some(Endpoint::ChainInfo) => {
            let body = format!(
                r#"{{"chain":"main","blocks":{},"headers":{},"initialblockdownload":{},"verificationprogress":{}}}"#,
                shared.blocks, shared.blocks, shared.ibd, shared.verification_progress
            );
            respond(writer, 200, "application/json", body.as_bytes())
        }
        Some(Endpoint::BlockHash) => match height.and_then(|h| shared.hash_by_height.get(&h)) {
            Some(hash) => respond(writer, 200, "text/plain", format!("{}\n", hash).as_bytes()),
            None => respond(writer, 404, "text/plain", b"Block not found\n"),
        },
        Some(Endpoint::Block) => {
            let hash = path
                .trim_start_matches("/rest/block/")
                .trim_end_matches(".json");
            match shared.body_by_hash.get(hash) {
                Some(body) => respond(writer, 200, "application/json", body.render().as_bytes()),
                None => respond(writer, 404, "text/plain", b"Block not found\n"),
            }
        }
        None => respond(writer, 404, "text/plain", b"Not found\n"),
    }
}

/// Takes the fault for `endpoint`, if one is due.
fn take_fault(shared: &Arc<Shared>, endpoint: Endpoint) -> Option<FaultKind> {
    let mut faults = shared.faults.lock().unwrap();
    let fault = faults.get_mut(&endpoint)?;
    if fault.times == 0 {
        return None;
    }
    if fault.times != usize::MAX {
        fault.times -= 1;
    }
    Some(fault.kind.clone())
}

fn apply_fault(writer: &mut TcpStream, kind: FaultKind) -> bool {
    match kind {
        FaultKind::Status(status) => respond(
            writer,
            status,
            "application/json",
            br#"{"error":"injected failure"}"#,
        ),
        FaultKind::DropConnection => false,
        // Handled before the normal answer in handle_request.
        FaultKind::Delay(_) => true,
        FaultKind::Body(body) => respond(writer, 200, "application/json", body.as_bytes()),
        FaultKind::Oversized(bytes) => respond_oversized(writer, bytes),
    }
}

/// Writes a response. Returns whether the connection should stay open.
fn respond(writer: &mut TcpStream, status: u16, content_type: &str, body: &[u8]) -> bool {
    let header = format!(
        "HTTP/1.1 {} {}\r\nContent-Type: {}\r\nContent-Length: {}\r\n\r\n",
        status,
        reason(status),
        content_type,
        body.len()
    );
    writer.write_all(header.as_bytes()).is_ok() && writer.write_all(body).is_ok()
}

/// Writes a response with a body of `bytes` bytes without holding all of it in
/// memory, so a test can push the client past its body size limit.
///
/// The body is a JSON object with one very long string value, so a client that
/// parses while it reads doesn't stop early on something that isn't JSON.
fn respond_oversized(writer: &mut TcpStream, bytes: usize) -> bool {
    const PREFIX: &[u8] = br#"{"filler":""#;
    let header = format!(
        "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {}\r\n\r\n",
        bytes
    );
    if writer.write_all(header.as_bytes()).is_err() || writer.write_all(PREFIX).is_err() {
        return false;
    }
    let chunk = vec![b'a'; 64 * 1024];
    let mut written = PREFIX.len();
    while written < bytes {
        let len = chunk.len().min(bytes - written);
        // The client gives up once it hits its limit, so a write error here
        // is the expected outcome and not a test failure.
        if writer.write_all(&chunk[..len]).is_err() {
            return false;
        }
        written += len;
    }
    false
}

fn reason(status: u16) -> &'static str {
    match status {
        200 => "OK",
        404 => "Not Found",
        500 => "Internal Server Error",
        503 => "Service Unavailable",
        _ => "Status",
    }
}
