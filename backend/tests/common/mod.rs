//! Shared helpers for the integration tests.
//!
//! The centerpiece is [`MockCore`], an in-process stand-in for Bitcoin Core's
//! REST interface. It speaks just enough HTTP/1.1 (with keep-alive) to serve
//! the three endpoints the backend uses:
//!
//! * `/rest/chaininfo.json`
//! * `/rest/blockhashbyheight/<height>.hex`
//! * `/rest/block/<hash>.json`
//!
//! Blocks come from the JSON fixtures in `testdata/`. A fixture can be served
//! at any height: the mock rewrites the `hash` and `height` fields of the
//! served JSON so that the block really is the block the client asked for.
//! That matters because the stats are built from the *JSON* height, not from
//! the height that was requested.
//!
//! Every request is counted and failures can be injected per endpoint, so a
//! test can assert how often the backend talked to the node and how it reacts
//! to a node that is slow, broken or gone.
#![allow(dead_code)]

